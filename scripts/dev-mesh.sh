#!/usr/bin/env bash
# Run a three-node Reticulum mesh on one machine:
#
#   A (rchatd) ──TCP── rnsd relay ──TCP── C (rchatd)
#
# A and C are ordinary leaf nodes; the relay is a plain `rnsd` with transport
# enabled, exactly the topology the mesh graph is meant to show as 2 hops.
# The leaves are configured through the engine's own interface API (the same
# rows production writes), not through RCHAT_RNS_* environment seeding.
#
#   ./scripts/dev-mesh.sh
#
# Then open the UI (cd apps/desktop && npm run dev) and connect to either leaf,
# or run the scripted check:
#
#   node scripts/smoke-mesh.mjs http://127.0.0.1:8791 .dev/mesh/a/token \
#     http://127.0.0.1:8793 .dev/mesh/c/token
#
# To fall back to local discovery without restarting either leaf:
#
#   node scripts/mesh-config.mjs http://127.0.0.1:8791 .dev/mesh/a/token discovery
#   node scripts/mesh-config.mjs http://127.0.0.1:8793 .dev/mesh/c/token discovery
#
# Ctrl-C stops all three processes.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PORT_A="${PORT_A:-8791}"
PORT_C="${PORT_C:-8793}"
RELAY_TCP="${RELAY_TCP:-4272}"
DEV="$ROOT/.dev/mesh"

command -v rnsd >/dev/null || {
  echo "rnsd is required: pip install rns" >&2
  exit 1
}

cargo build -q -p rchatd

rm -rf "$DEV"
mkdir -p "$DEV/relay" "$DEV/a" "$DEV/c"

cat > "$DEV/relay/config" <<EOF
# Generated by scripts/dev-mesh.sh
[reticulum]
  enable_transport = Yes
  share_instance = No
  panic_on_interface_error = No

[logging]
  loglevel = 3

[interfaces]
  [[Leaves]]
    type = TCPServerInterface
    interface_enabled = True
    listen_ip = 127.0.0.1
    listen_port = $RELAY_TCP
EOF

PIDS=()
cleanup() {
  trap - EXIT INT TERM
  for pid in "${PIDS[@]:-}"; do
    kill "$pid" 2>/dev/null || true
  done
  wait 2>/dev/null || true
}
trap cleanup EXIT INT TERM

rnsd --config "$DEV/relay" > "$DEV/relay.log" 2>&1 &
PIDS+=($!)
sleep 2

./target/debug/rchatd --data-dir "$DEV/a" --port "$PORT_A" > "$DEV/a.log" 2>&1 &
PIDS+=($!)

./target/debug/rchatd --data-dir "$DEV/c" --port "$PORT_C" > "$DEV/c.log" 2>&1 &
PIDS+=($!)

wait_token() {
  local path="$1"
  for _ in $(seq 1 100); do
    [ -s "$path" ] && return 0
    sleep 0.1
  done
  echo "timed out waiting for $path" >&2
  return 1
}

wait_token "$DEV/a/token"
wait_token "$DEV/c/token"

# Store-owned rows: a Relay TCP client on each leaf, discovery off.
node scripts/mesh-config.mjs "http://127.0.0.1:$PORT_A" "$DEV/a/token" relay "127.0.0.1:$RELAY_TCP"
node scripts/mesh-config.mjs "http://127.0.0.1:$PORT_C" "$DEV/c/token" relay "127.0.0.1:$RELAY_TCP"

sleep 2

address() {
  curl -s "http://127.0.0.1:$1/health" | grep -o '"address":"[a-f0-9]*"' | cut -d'"' -f4
}

echo
echo "  A  http://127.0.0.1:$PORT_A   token: $(cat "$DEV/a/token")"
echo "     address: $(address "$PORT_A")"
echo "  C  http://127.0.0.1:$PORT_C   token: $(cat "$DEV/c/token")"
echo "     address: $(address "$PORT_C")"
echo "  relay      $DEV/relay/config (tcp 127.0.0.1:$RELAY_TCP, transport enabled)"
echo
echo "  Scripted check:"
echo "    node scripts/smoke-mesh.mjs http://127.0.0.1:$PORT_A $DEV/a/token \\"
echo "      http://127.0.0.1:$PORT_C $DEV/c/token"
echo
echo "  Start the UI:  cd apps/desktop && npm run dev"
echo "  Logs:          $DEV/a.log  $DEV/c.log  $DEV/relay.log"
echo "  Ctrl-C stops all three nodes."
echo

wait
