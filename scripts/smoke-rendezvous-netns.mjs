// Relay-free discovery across a network boundary, on one Linux machine.
//
//   node scripts/smoke-rendezvous-netns.mjs
//
// Leaf A runs on the host. Leaf C runs inside a network namespace connected by
// a veth pair, so two full Reticulum instances can run AutoInterface on one
// machine: the fixed AutoInterface data port is per network namespace, not per
// host. A tiny forwarder inside the namespace exposes C's loopback HTTP/WS port
// on the veth address, so the orchestrator drives both leaves through the same
// client.
//
// Both leaves start from a hand-written config with one AutoInterface row and
// no relay, using a per-run `group_id`, so a device on the physical LAN cannot
// make the test pass. The assertions are the product: each leaf has exactly one
// AutoInterface row, a direct path exists without a relay, a message crosses,
// and neither interface list ever holds the other leaf's Reticulum address.
//
// This script needs `ip netns` write access (root or passwordless sudo) and
// IPv6 link-local addressing on the veth, because RNS discovers over IPv6
// multicast. When either is unavailable it prints one line naming the unmet
// requirement and exits 0: a missing capability is not a test failure. The
// capability probe is unit-tested by scripts/smoke-rendezvous-netns.test.mjs.
//
// Cleanup (namespace, veth, forwarder, leaves) is unconditional: on success,
// failure, SIGINT and SIGTERM. A leftover namespace would break the next run,
// and a leftover AutoInterface process would hold the data port this script
// exists to work around.
import { spawn, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { connect, sleep, until } from "./lib.mjs";
import { waitForBridge } from "./mesh-config.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEV =
  process.env.NETNS_RENDEZVOUS_DIR || path.join(ROOT, ".dev", "rendezvous-netns");
// Linux limits interface names to 15 characters; pid fits with room to spare.
const NS = `rchat-smoke-${process.pid}`;
const HOST_VETH = `rchat-h${process.pid}`;
const NS_VETH = `rchat-n${process.pid}`;
const GROUP = `rchat-smoke-${process.pid}`;
const HOST_ADDR = "10.203.71.1";
const NS_ADDR = "10.203.71.2";

function freePort() {
  return 20000 + Math.floor(Math.random() * 20000);
}

const PORT_A = Number(process.env.PORT_A || freePort());
const PORT_C = Number(process.env.PORT_C || freePort());

const defaultExec = (command, args) =>
  spawnSync(command, args, { encoding: "utf8" });

function withSudo(uid, argv) {
  return uid === 0 ? argv : ["sudo", "-n", ...argv];
}

/// What stops this runner from working here, as one short phrase. Exported so
/// the skip path is tested on a machine that has no namespaces at all.
export function capabilityProblem({
  platform = process.platform,
  uid = typeof process.getuid === "function" ? process.getuid() : null,
  exec = defaultExec,
} = {}) {
  if (platform !== "linux") return "network namespaces are Linux-only";
  const ip = exec("ip", ["-V"]);
  if (!ip || ip.status !== 0) return "the ip command is not installed";
  if (uid !== 0) {
    const sudo = exec("sudo", ["-n", "true"]);
    if (!sudo || sudo.status !== 0) {
      return "creating a network namespace needs root or passwordless sudo";
    }
  }
  const probe = withSudo(uid, ["ip", "netns", "list"]);
  const netns = exec(probe[0], probe.slice(1));
  if (!netns || netns.status !== 0) return "ip netns is unavailable on this host";
  return null;
}

function ensureBinary() {
  const binary = process.env.RCHATD || path.join(ROOT, "target", "debug", "rchatd");
  if (fs.existsSync(binary)) return binary;
  console.log("building rchatd…");
  const built = spawnSync("cargo", ["build", "-q", "-p", "rchatd"], {
    cwd: ROOT,
    stdio: "inherit",
  });
  if (built.status !== 0) throw new Error("cargo build failed");
  return binary;
}

// Production never seeds interfaces from the environment; a caller's shell
// must not silently switch these leaves to the old seed path.
const cleanEnv = Object.fromEntries(
  Object.entries(process.env).filter(([key]) => !key.startsWith("RCHAT_RNS_")),
);

function seedConfig(name) {
  const dir = path.join(DEV, name, "rns");
  fs.mkdirSync(dir, { recursive: true });
  const lines = [
    "# Generated by scripts/smoke-rendezvous-netns.mjs",
    "[reticulum]",
    "  enable_transport = No",
    "  share_instance = No",
    "  panic_on_interface_error = No",
    "",
    "[logging]",
    "  loglevel = 3",
    "",
    "[interfaces]",
    "  [[AutoInterface]]",
    "    type = AutoInterface",
    "    interface_enabled = True",
    `    group_id = ${GROUP}`,
    "",
  ];
  fs.writeFileSync(path.join(dir, "config"), lines.join("\n"));
}

/// One forwarder beside leaf C: the host can reach the namespace's veth
/// address, while rchatd binds loopback only.
const FORWARDER = `
const net = require("node:net");
const host = process.argv[1];
const listenPort = Number(process.argv[2]);
const targetPort = Number(process.argv[3]);
const server = net.createServer((client) => {
  const upstream = net.connect(targetPort, "127.0.0.1");
  client.pipe(upstream).pipe(client);
  client.on("error", () => upstream.destroy());
  upstream.on("error", () => client.destroy());
});
server.on("error", (err) => { console.error(String(err)); process.exit(1); });
server.listen(listenPort, host);
for (const signal of ["SIGINT", "SIGTERM"]) process.on(signal, () => process.exit(0));
`;

export async function main({
  platform = process.platform,
  uid = typeof process.getuid === "function" ? process.getuid() : null,
  exec = defaultExec,
  log = console.log,
} = {}) {
  const problem = capabilityProblem({ platform, uid, exec });
  if (problem) {
    log(`smoke-rendezvous-netns: skipped (${problem})`);
    return 0;
  }

  const prefix = uid === 0 ? [] : ["sudo", "-n"];
  const children = [];
  let namespace = false;
  let veth = false;
  let cleaned = false;
  let stopping = false;

  function run(argv, { ns = null, allowFail = false } = {}) {
    const command = ns
      ? [...prefix, "ip", "netns", "exec", ns, ...argv]
      : [...prefix, ...argv];
    const result = spawnSync(command[0], command.slice(1), {
      encoding: "utf8",
    });
    if (!allowFail && result.status !== 0) {
      const detail = (result.stderr || result.stdout || "").trim();
      throw new Error(`${command.join(" ")} failed${detail ? `: ${detail}` : ""}`);
    }
    return result;
  }

  function launch(name, argv, inNamespace) {
    const command = inNamespace
      ? [...prefix, "ip", "netns", "exec", NS, ...argv]
      : [...prefix, ...argv];
    const out = fs.openSync(path.join(DEV, `${name}.log`), "a");
    const child = spawn(command[0], command.slice(1), {
      cwd: ROOT,
      env: cleanEnv,
      stdio: ["ignore", out, out],
    });
    child.label = name;
    child.on("exit", (code, signal) => {
      if (!stopping) console.log(`[${name}] exited (${signal ?? code})`);
    });
    children.push(child);
    return child;
  }

  async function stop(child) {
    if (!child || child.exitCode != null) return;
    const done = new Promise((resolve) => child.once("exit", resolve));
    child.kill("SIGTERM");
    await Promise.race([done, sleep(4000)]);
    if (child.exitCode == null) child.kill("SIGKILL");
    await Promise.race([done, sleep(1000)]);
  }

  async function cleanup() {
    if (cleaned) return;
    cleaned = true;
    stopping = true;
    await Promise.all([...children].reverse().map((child) => stop(child)));
    if (namespace) run(["ip", "netns", "del", NS], { allowFail: true });
    if (veth) run(["ip", "link", "del", HOST_VETH], { allowFail: true });
  }

  const onSignal = (code) => {
    cleanup().finally(() => process.exit(code));
  };
  const onSigint = () => onSignal(130);
  const onSigterm = () => onSignal(143);
  process.on("SIGINT", onSigint);
  process.on("SIGTERM", onSigterm);

  let a = null;
  let c = null;

  async function connectLeaf(name, base) {
    const token = await until(
      () => {
        try {
          return (
            fs.readFileSync(path.join(DEV, name, "token"), "utf8").trim() || null
          );
        } catch {
          return null;
        }
      },
      { timeoutMs: 30000, intervalMs: 100 },
    );
    const api = await until(
      async () => {
        let client;
        try {
          client = connect(base, token);
          await client.hello;
          return client;
        } catch {
          client?.close();
          return null;
        }
      },
      { timeoutMs: 60000, intervalMs: 250 },
    );
    const address = await until(
      async () => {
        const { mesh } = await api.call({ cmd: "mesh_status" });
        return mesh.address ?? null;
      },
      { timeoutMs: 60000, intervalMs: 250 },
    );
    const leaf = { name, base, token, api, address };
    await waitForBridge(api, 90000);
    return leaf;
  }

  async function waitDirect(leaf, peerAddress) {
    return until(
      async () => {
        const { paths } = await leaf.api.call({ cmd: "mesh_paths", limit: 500 });
        return (
          (paths ?? []).find(
            (entry) => entry.destination === peerAddress && entry.hops === 1,
          ) ?? null
        );
      },
      { timeoutMs: 120000, intervalMs: 500 },
    );
  }

  async function discoveryRows(leaf, own, peer) {
    const { interfaces } = await leaf.api.call({ cmd: "list_interfaces" });
    if (interfaces.length !== 1) {
      throw new Error(
        `${leaf.name} has ${interfaces.length} interface rows, expected one discovery row`,
      );
    }
    const only = interfaces[0];
    if (only.kind !== "AutoInterface") {
      throw new Error(`${leaf.name} started with ${only.kind}, not AutoInterface`);
    }
    if (only.config?.group_id !== GROUP) {
      throw new Error(
        `${leaf.name} uses group ${only.config?.group_id}, not the isolated ${GROUP}`,
      );
    }
    if (interfaces.some((row) => String(row.kind).includes("TCP"))) {
      throw new Error(`${leaf.name} still has a relay row`);
    }
    const text = JSON.stringify(interfaces);
    if (text.includes(own) || text.includes(peer)) {
      throw new Error(`${leaf.name} stored a peer's Reticulum address in its rows`);
    }
    return only;
  }

  async function exchange(from, to, label) {
    const body = `${label} ${Date.now()}`;
    const { conversation } = await from.api.call({
      cmd: "open_direct",
      peer_id: to.address,
    });
    const sent = await from.api.call({
      cmd: "send_message",
      conversation_id: conversation.id,
      body,
    });
    await to.api.waitFor(
      (event) => event.name === "message.new" && event.data.message.body === body,
      60000,
    );
    await from.api.waitFor(
      (event) =>
        event.name === "message.state" &&
        event.data.id === sent.message.id &&
        event.data.state === "delivered",
      60000,
    );
    return sent.message.id;
  }

  try {
    const binary = ensureBinary();
    fs.rmSync(DEV, { recursive: true, force: true });
    fs.mkdirSync(DEV, { recursive: true });
    console.log(
      `namespace ${NS}: ${HOST_ADDR} (host) <-> ${NS_ADDR} (leaf C); group ${GROUP}`,
    );

    run(["ip", "netns", "add", NS]);
    namespace = true;
    run(["ip", "link", "add", HOST_VETH, "type", "veth", "peer", "name", NS_VETH]);
    veth = true;
    run(["ip", "link", "set", NS_VETH, "netns", NS]);
    run(["ip", "addr", "add", `${HOST_ADDR}/30`, "dev", HOST_VETH]);
    run(["sysctl", "-q", "-w", `net.ipv6.conf.${HOST_VETH}.disable_ipv6=0`], {
      allowFail: true,
    });
    run(["ip", "link", "set", HOST_VETH, "up"]);
    run(["ip", "addr", "add", `${NS_ADDR}/30`, "dev", NS_VETH], { ns: NS });
    run(["sysctl", "-q", "-w", `net.ipv6.conf.${NS_VETH}.disable_ipv6=0`], {
      ns: NS,
      allowFail: true,
    });
    run(["ip", "link", "set", "lo", "up"], { ns: NS });
    run(["ip", "link", "set", NS_VETH, "up"], { ns: NS });

    // RNS AutoInterface discovers over IPv6 link-local multicast. A silently
    // IPv4-only veth would fail in a way that looks like an rchat bug.
    const hasIpv6 = async (dev, ns) => {
      const deadline = Date.now() + 5000;
      while (Date.now() < deadline) {
        const result = run(
          ["ip", "-6", "addr", "show", "dev", dev, "scope", "link"],
          { ns, allowFail: true },
        );
        if (/inet6\s+fe80::/i.test(result.stdout || "")) return true;
        await sleep(200);
      }
      return false;
    };
    if (!(await hasIpv6(HOST_VETH, null)) || !(await hasIpv6(NS_VETH, NS))) {
      await cleanup();
      log(
        "smoke-rendezvous-netns: skipped (IPv6 link-local addressing is unavailable on the veth)",
      );
      return 0;
    }

    a = await (async () => {
      fs.mkdirSync(path.join(DEV, "a"), { recursive: true });
      seedConfig("a");
      launch("a", [binary, "--data-dir", path.join(DEV, "a"), "--port", String(PORT_A)], false);
      return connectLeaf("a", `http://127.0.0.1:${PORT_A}`);
    })();
    launch(
      "forwarder",
      [process.execPath, "-e", FORWARDER, NS_ADDR, String(PORT_C), String(PORT_C)],
      true,
    );
    c = await (async () => {
      fs.mkdirSync(path.join(DEV, "c"), { recursive: true });
      seedConfig("c");
      launch(
        "c",
        [binary, "--data-dir", path.join(DEV, "c"), "--port", String(PORT_C)],
        true,
      );
      return connectLeaf("c", `http://${NS_ADDR}:${PORT_C}`);
    })();
    console.log("A:", a.address, "| C:", c.address);

    await discoveryRows(a, a.address, c.address);
    await discoveryRows(c, c.address, a.address);

    const pathA = await waitDirect(a, c.address);
    const pathC = await waitDirect(c, a.address);
    console.log(
      `  direct discovery: A->C via ${pathA.interface}, C->A via ${pathC.interface}`,
    );

    await exchange(a, c, "rendezvous netns");
    // Re-read after delivery: a late announce must not have written an address
    // into a row either.
    await discoveryRows(a, a.address, c.address);
    await discoveryRows(c, c.address, a.address);
    console.log("\nsmoke-rendezvous-netns: OK");
    return 0;
  } finally {
    try {
      a?.api.close();
      c?.api.close();
    } catch {
      /* already closed */
    }
    await cleanup();
    process.removeListener("SIGINT", onSigint);
    process.removeListener("SIGTERM", onSigterm);
  }
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  main()
    .then((code) => {
      process.exitCode = code;
    })
    .catch((err) => {
      console.error(`smoke-rendezvous-netns: ${err?.message ?? err}`);
      process.exitCode = 1;
    });
}
